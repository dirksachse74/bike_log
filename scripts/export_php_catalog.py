"""Write the reference catalog (part types, maintenance actions, default service rules) as JSON for
the PHP version (php/app/catalog.json), so both apps share one source: backend/bikelog/catalog.py.

Run from the repo root:  python scripts/export_php_catalog.py
"""
from __future__ import annotations

import dataclasses
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from bikelog import catalog  # noqa: E402


def _plain(obj):
    if dataclasses.is_dataclass(obj):
        return {k: _plain(v) for k, v in dataclasses.asdict(obj).items()}
    if isinstance(obj, (list, tuple)):
        return [_plain(v) for v in obj]
    if isinstance(obj, dict):
        return {k: _plain(v) for k, v in obj.items()}
    return obj


def main() -> None:
    data = {
        "_comment": "Generated by scripts/export_php_catalog.py from backend/bikelog/catalog.py. Do not edit.",
        "component_types": [_plain(t) for t in catalog.COMPONENT_TYPES.values()],
        "actions": [_plain(a) for a in catalog.ACTIONS.values()],
        "default_rules": [_plain(r) for r in catalog.DEFAULT_RULES],
        "ride_sport_types": list(catalog.RIDE_SPORT_TYPES),
    }
    from bikelog.groupset_templates import TEMPLATES
    data["groupset_templates"] = [_plain(t) for t in TEMPLATES.values()]
    data["dispositions"] = _plain(getattr(catalog, "DISPOSITIONS", {}))
    data["stock_units"] = _plain(catalog.STOCK_UNITS)
    data["incident_types"] = dict(catalog.INCIDENT_TYPES)
    data["incident_options"] = {k: [_plain(o) for o in v] for k, v in catalog.INCIDENT_OPTIONS.items()}
    data["tire_setups"] = dict(catalog.TIRE_SETUPS)
    out = ROOT / "php" / "app" / "catalog.json"
    out.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}: {len(data['component_types'])} types, "
          f"{len(data['actions'])} actions, {len(data['default_rules'])} rules")


if __name__ == "__main__":
    main()
